-- ============================================================================
-- V1__init.sql - Personal Web App schema (Table Design, Phase 2)
-- Written in portable SQL so it runs on PostgreSQL (production / Neon)
-- and on H2 in PostgreSQL mode (local profile "h2" and integration tests).
-- ============================================================================

-- 1. Users
CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               VARCHAR(255) NOT NULL,
    password_hash       VARCHAR(100) NOT NULL,
    mobile              VARCHAR(10)  NOT NULL,
    name                VARCHAR(100),
    sex                 VARCHAR(20),
    date_of_birth       DATE,
    profile_photo_url   VARCHAR(500),
    password_changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_mobile UNIQUE (mobile),
    CONSTRAINT ck_users_sex CHECK (sex IS NULL OR sex IN ('MALE', 'FEMALE', 'OTHER', 'PREFER_NOT_TO_SAY'))
);

-- 2. Password reset tokens (only the SHA-256 hash of the token is stored)
CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    token_hash  VARCHAR(64)  NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at     TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_reset_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_reset_token_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_reset_tokens_user ON password_reset_tokens (user_id);

-- 3. Saved passwords (AES-256-GCM encrypted)
CREATE TABLE vault_entries (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT        NOT NULL,
    source             VARCHAR(150)  NOT NULL,
    login_id           VARCHAR(255)  NOT NULL,
    password_encrypted VARCHAR(2048) NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_vault_user_source_login UNIQUE (user_id, source, login_id),
    CONSTRAINT fk_vault_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_vault_user_created ON vault_entries (user_id, created_at);

-- 4. Notes
CREATE TABLE notes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT         NOT NULL,
    topic       VARCHAR(200)   NOT NULL,
    content     VARCHAR(10000) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notes_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_notes_user_created ON notes (user_id, created_at);

-- 5. Workout categories (fixed list)
CREATE TABLE workout_categories (
    id    INTEGER     NOT NULL PRIMARY KEY,
    name  VARCHAR(50) NOT NULL,
    CONSTRAINT uk_workout_categories_name UNIQUE (name)
);
INSERT INTO workout_categories (id, name) VALUES
    (1, 'Chest'), (2, 'Back'), (3, 'Shoulders'), (4, 'Biceps'), (5, 'Triceps'),
    (6, 'Legs'), (7, 'ABS'), (8, 'Cardio'), (9, 'Other');

-- 6. Shared workout library (no owner)
CREATE TABLE workouts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  INTEGER       NOT NULL,
    name         VARCHAR(150)  NOT NULL,
    reps         INTEGER       NOT NULL,
    weight_kg    NUMERIC(6, 2),
    image_url    VARCHAR(500),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_workouts_reps CHECK (reps > 0),
    CONSTRAINT ck_workouts_weight CHECK (weight_kg IS NULL OR weight_kg > 0),
    CONSTRAINT fk_workouts_category FOREIGN KEY (category_id) REFERENCES workout_categories (id)
);
CREATE INDEX idx_workouts_category ON workouts (category_id);

-- 7. Each user's weekly workout plan
CREATE TABLE workout_plan_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT   NOT NULL,
    day_of_week  INTEGER  NOT NULL,
    workout_id   BIGINT   NOT NULL,
    position     INTEGER  NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_workout_plan_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT fk_workout_plan_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_workout_plan_workout FOREIGN KEY (workout_id) REFERENCES workouts (id) ON DELETE RESTRICT
);
CREATE INDEX idx_workout_plan_user_day ON workout_plan_entries (user_id, day_of_week, position);
CREATE INDEX idx_workout_plan_workout ON workout_plan_entries (workout_id);

-- 8. Food categories (fixed list)
CREATE TABLE food_categories (
    id    INTEGER     NOT NULL PRIMARY KEY,
    name  VARCHAR(50) NOT NULL,
    CONSTRAINT uk_food_categories_name UNIQUE (name)
);
INSERT INTO food_categories (id, name) VALUES
    (1, 'Breakfast'), (2, 'Lunch'), (3, 'Dinner'), (4, 'Snacks'),
    (5, 'Fruits'), (6, 'Drinks'), (7, 'Other');

-- 9. Shared food library (no owner)
CREATE TABLE foods (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  INTEGER       NOT NULL,
    dish_name    VARCHAR(150)  NOT NULL,
    weight_g     NUMERIC(8, 2) NOT NULL,
    calories     NUMERIC(8, 2) NOT NULL,
    protein_g    NUMERIC(7, 2) NOT NULL,
    fiber_g      NUMERIC(7, 2) NOT NULL,
    image_url    VARCHAR(500),
    others       VARCHAR(1000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_foods_weight CHECK (weight_g > 0),
    CONSTRAINT ck_foods_calories CHECK (calories > 0),
    CONSTRAINT ck_foods_protein CHECK (protein_g >= 0),
    CONSTRAINT ck_foods_fiber CHECK (fiber_g >= 0),
    CONSTRAINT fk_foods_category FOREIGN KEY (category_id) REFERENCES food_categories (id)
);
CREATE INDEX idx_foods_category ON foods (category_id);

-- 10. Each user's weekly diet plan
CREATE TABLE food_plan_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT   NOT NULL,
    day_of_week  INTEGER  NOT NULL,
    food_id      BIGINT   NOT NULL,
    position     INTEGER  NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_food_plan_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT fk_food_plan_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_food_plan_food FOREIGN KEY (food_id) REFERENCES foods (id) ON DELETE RESTRICT
);
CREATE INDEX idx_food_plan_user_day ON food_plan_entries (user_id, day_of_week, position);
CREATE INDEX idx_food_plan_food ON food_plan_entries (food_id);
